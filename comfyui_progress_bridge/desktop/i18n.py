def localized_result(language: str, code: str) -> str:
    """Return locale-owned text for every public adapter result code."""
    catalog = RESULT_MESSAGES.get(language, RESULT_MESSAGES["en-US"])
    return catalog.get(code, catalog["api_error"])


class Translator:
    def __init__(self, language: str) -> None:
        if language not in LANGUAGES:
            raise ValueError(f"unsupported language: {language}")
        self.language = language

    def __call__(self, key: str, **values: object) -> str:
        text = LANGUAGES[self.language][key]
        return text.format(**values) if values else text
